-- 탈퇴 사유 (user 모듈). 서비스 개선 통계용이라 회원과 연결하지 않습니다.
-- 회원 id를 남기지 않고, 시각 대신 날짜만 둡니다. 정확한 시각을 남기면 users.withdrawal_requested_at과 맞춰 보고
-- 누구의 사유인지 알아낼 수 있기 때문입니다. (#106의 V10 다음 번호입니다. #106이 먼저 병합되어야 합니다)
CREATE TABLE withdrawal_reasons (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason       VARCHAR(30) NOT NULL,
    -- '기타'를 고르면 필수, 그 밖에는 적은 경우에만. 회원이 직접 개인정보를 적을 수는 있습니다
    detail       TEXT,
    requested_on DATE        NOT NULL,

    CONSTRAINT ck_withdrawal_reasons_reason
        CHECK (reason IN ('RARELY_USED', 'MISSING_FEATURE', 'PRIVACY', 'OTHER_SERVICE', 'ETC'))
);
