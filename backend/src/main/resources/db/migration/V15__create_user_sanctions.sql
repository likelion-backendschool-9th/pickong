-- created_at을 즉시 적용되는 제재의 시작 시각으로 재사용합니다.
-- suspended_until은 원래 만료 예정 시각이며, 해제/BAN 전환 뒤에도 보존합니다.
-- ended_at/end_reason은 실제 종료를, revoked_*는 관리자 해제만 나타냅니다.

CREATE TABLE user_sanctions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT      NOT NULL,
    type                VARCHAR(20) NOT NULL,
    reason              TEXT        NOT NULL,
    suspended_until     TIMESTAMPTZ,
    admin_id            BIGINT      NOT NULL,
    revoked_at          TIMESTAMPTZ,
    revoked_by_admin_id BIGINT,
    revoke_reason       TEXT,
    source_report_id    BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at            TIMESTAMPTZ,
    end_reason          VARCHAR(30),

    -- users는 탈퇴 시에도 행을 남기고 익명화합니다. 제재/관리자/신고 이력은 연쇄 삭제하지 않습니다.
    CONSTRAINT fk_user_sanctions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_sanctions_admin FOREIGN KEY (admin_id) REFERENCES admins (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_sanctions_revoked_by_admin FOREIGN KEY (revoked_by_admin_id) REFERENCES admins (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_sanctions_source_report FOREIGN KEY (source_report_id) REFERENCES reports (id) ON DELETE RESTRICT,
    -- PostgreSQL UNIQUE는 NULL 여러 개를 허용하므로 직접 처리/반복 경고는 막지 않습니다.
    CONSTRAINT uk_user_sanctions_source_report UNIQUE (source_report_id),
    CONSTRAINT ck_user_sanctions_type CHECK (type IN ('WARNING', 'SUSPEND', 'BAN')),
    CONSTRAINT ck_user_sanctions_reason CHECK (
        char_length(reason) <= 200
        AND btrim(reason, U&'\0009\000A\000B\000C\000D\001C\001D\001E\001F\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000') <> ''
    ),
    CONSTRAINT ck_user_sanctions_period CHECK (
        (type = 'SUSPEND' AND suspended_until IS NOT NULL AND suspended_until > created_at)
        OR (type IN ('WARNING', 'BAN') AND suspended_until IS NULL)
    ),
    CONSTRAINT ck_user_sanctions_end_state CHECK (
        (ended_at IS NULL AND end_reason IS NULL)
        OR (ended_at IS NOT NULL AND ended_at >= created_at AND end_reason IS NOT NULL
            AND end_reason IN ('EXPIRED', 'REVOKED', 'SUPERSEDED_BY_BAN'))
    ),
    CONSTRAINT ck_user_sanctions_expiry CHECK (
        end_reason IS DISTINCT FROM 'EXPIRED'
        OR (type = 'SUSPEND' AND ended_at = suspended_until)
    ),
    CONSTRAINT ck_user_sanctions_superseded CHECK (
        end_reason IS DISTINCT FROM 'SUPERSEDED_BY_BAN' OR type = 'SUSPEND'
    ),
    CONSTRAINT ck_user_sanctions_revocation CHECK (
        (end_reason IS NOT NULL AND end_reason = 'REVOKED' AND revoked_at IS NOT NULL AND revoked_at = ended_at
            AND revoked_by_admin_id IS NOT NULL)
        OR (end_reason IS DISTINCT FROM 'REVOKED' AND revoked_at IS NULL
            AND revoked_by_admin_id IS NULL AND revoke_reason IS NULL)
    ),
    CONSTRAINT ck_user_sanctions_revoke_reason CHECK (
        revoke_reason IS NULL OR (
            char_length(revoke_reason) <= 200
            AND btrim(revoke_reason, U&'\0009\000A\000B\000C\000D\001C\001D\001E\001F\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000') <> ''
        )
    )
);

-- '미종료'와 '현재 유효'는 다릅니다. now()에 의존하는 인덱스는 사용하지 않습니다.
-- 후속 UseCase는 user 공개 포트로 회원 행을 잠그고 만료된 SUSPEND를 EXPIRED로 종료한 뒤 새 제재를 등록합니다.
-- BAN 전환은 같은 트랜잭션에서 기존 SUSPEND를 SUPERSEDED_BY_BAN으로 종료한 뒤 BAN을 등록합니다.
CREATE UNIQUE INDEX ux_user_sanctions_open_restriction
    ON user_sanctions (user_id)
    WHERE type IN ('SUSPEND', 'BAN') AND ended_at IS NULL;

CREATE INDEX ix_user_sanctions_user_created_at ON user_sanctions (user_id, created_at DESC, id DESC);
CREATE INDEX ix_user_sanctions_admin_created_at ON user_sanctions (admin_id, created_at DESC, id DESC);
CREATE INDEX ix_user_sanctions_revoked_by_admin ON user_sanctions (revoked_by_admin_id) WHERE revoked_by_admin_id IS NOT NULL;
CREATE INDEX ix_user_sanctions_open_expiry ON user_sanctions (suspended_until, user_id) WHERE type = 'SUSPEND' AND ended_at IS NULL;
