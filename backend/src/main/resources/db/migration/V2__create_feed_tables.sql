-- ── feeds ─────────────────────────────────────────────────
CREATE TABLE feeds (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       UUID        NOT NULL DEFAULT gen_random_uuid(),
    user_id         BIGINT      NOT NULL REFERENCES users(id),
    content         TEXT,
    visibility      VARCHAR(20) NOT NULL DEFAULT 'PUBLIC',
    like_count      BIGINT      NOT NULL DEFAULT 0,
    comment_count   BIGINT      NOT NULL DEFAULT 0,
    bookmark_count  BIGINT      NOT NULL DEFAULT 0,
    is_sponsored    BOOLEAN     NOT NULL DEFAULT false,
    sponsor_name    VARCHAR(100),
    hidden_at       TIMESTAMPTZ,
    deleted_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_feeds_public_id UNIQUE (public_id)
);

-- ── feed_photos ───────────────────────────────────────────
CREATE TABLE feed_photos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id         BIGINT NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
    media_file_id   BIGINT NOT NULL,
    sort_order      INT    NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── feed_places ───────────────────────────────────────────
CREATE TABLE feed_places (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id     BIGINT NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
    place_id    BIGINT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_feed_places UNIQUE (feed_id, place_id)
);

-- ── comments ──────────────────────────────────────────────
CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id     BIGINT NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(id),
    parent_id   BIGINT REFERENCES comments(id) ON DELETE CASCADE,
    content     TEXT   NOT NULL,
    like_count  BIGINT NOT NULL DEFAULT 0,
    hidden_at   TIMESTAMPTZ,
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── feed_likes ────────────────────────────────────────────
CREATE TABLE feed_likes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id     BIGINT NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_feed_likes UNIQUE (feed_id, user_id)
);

-- ── feed_bookmarks ────────────────────────────────────────
CREATE TABLE feed_bookmarks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id     BIGINT NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_feed_bookmarks UNIQUE (feed_id, user_id)
);

-- ── comment_likes ─────────────────────────────────────────
CREATE TABLE comment_likes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id  BIGINT NOT NULL REFERENCES comments(id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_comment_likes UNIQUE (comment_id, user_id)
);
