-- 업로드한 사진 한 장의 기록. media 모듈의 MediaFileJpaEntity와 같은 컬럼만 만듦
-- 흐름: Presigned URL 발급(PENDING) → 업로드 확인(UPLOADED 또는 FAILED) → 게시물에 연결

CREATE TABLE media_files (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 올린 사람. 탈퇴해도 users 행은 남는 정책이라 삭제 연쇄는 두지 않음
    user_id      BIGINT       NOT NULL REFERENCES users (id),
    status       VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    -- R2 안의 파일 이름 (예: feeds/랜덤UUID.jpg). 회원 id를 넣지 않아 주소로 주인을 알 수 없음
    storage_key  VARCHAR(255),
    -- 보는 주소 (R2_PUBLIC_BASE_URL + storage_key)
    url          TEXT,
    mime_type    VARCHAR(100),
    -- 업로드 확인 때 R2에서 읽은 실제 크기
    size_bytes   BIGINT,
    -- 이미지 처리 기능이 생기면 채움
    width        INTEGER,
    height       INTEGER,
    retry_count  INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_media_files_storage_key UNIQUE (storage_key),
    -- MediaStatus와 같은 값만 허용
    CONSTRAINT ck_media_files_status CHECK (status IN ('PENDING', 'UPLOADED', 'PROCESSED', 'FAILED')),
    CONSTRAINT ck_media_files_size CHECK (size_bytes IS NULL OR size_bytes >= 0),
    CONSTRAINT ck_media_files_retry_count CHECK (retry_count >= 0),
    CONSTRAINT ck_media_files_dimensions CHECK ((width IS NULL OR width > 0) AND (height IS NULL OR height > 0))
);

-- 정리 스케줄러가 만든 지 오래된 PENDING 파일을 찾을 때 씀
CREATE INDEX ix_media_files_status_created ON media_files (status, created_at);
