-- DM 대화방 · 참여자 · 메시지 (blueprint backend 5.4, common 5.9)
-- 지금은 1:1(DIRECT)만 API가 있고, 그룹(GROUP)은 별도 이슈에서 관리 컬럼(방장 등)과 함께 엽니다.
-- 첨부 컬럼은 메시지 보내기(STOMP)를 만들 때 형식을 확정하고 추가합니다.

CREATE TABLE conversations (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- DIRECT | GROUP
    type        VARCHAR(20)  NOT NULL,
    -- 그룹 이름. DIRECT는 NULL
    title       VARCHAR(50),
    -- 1:1 대화방 중복 방지 키 "작은 회원 id:큰 회원 id". GROUP은 NULL
    direct_key  VARCHAR(41),
    created_by  BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_conversations_type CHECK (type IN ('DIRECT', 'GROUP')),
    -- DIRECT만 direct_key가 있고 title이 없음
    CONSTRAINT ck_conversations_direct_key CHECK ((type = 'DIRECT') = (direct_key IS NOT NULL)),
    CONSTRAINT ck_conversations_direct_title CHECK (type = 'GROUP' OR title IS NULL),
    -- 같은 두 사람의 1:1 대화방은 하나. 동시에 열어도 INSERT ... ON CONFLICT로 하나만 생김
    CONSTRAINT uk_conversations_direct_key UNIQUE (direct_key)
);

CREATE TABLE conversation_members (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id       BIGINT       NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    user_id               BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- 마지막으로 읽은 메시지. 뒤로 가지 않음 (FK는 messages를 만든 뒤 아래에서 추가)
    last_read_message_id  BIGINT,
    -- 참여 시각. 나갔다가 다시 열면 그 시각으로 바뀌고, 이 시각 이후 메시지만 보임
    joined_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- 나간 시각. NULL이면 참여 중
    left_at               TIMESTAMPTZ,

    CONSTRAINT uk_conversation_members_conversation_user UNIQUE (conversation_id, user_id)
);

-- 내 대화 목록 조회용 (참여 중인 대화방만)
CREATE INDEX ix_conversation_members_user_active ON conversation_members (user_id) WHERE left_at IS NULL;

CREATE TABLE messages (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id    BIGINT       NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- 프론트가 메시지마다 만드는 UUID. 재전송 · 재연결로 같은 메시지가 두 번 저장되지 않게 함 (blueprint 8.1 #10)
    client_message_id  UUID         NOT NULL,
    content            TEXT,
    deleted_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_messages_sender_client_message UNIQUE (sender_id, client_message_id),
    -- 첨부가 생기기 전까지는 본문이 반드시 있음. 첨부를 추가할 때 "본문 또는 첨부 하나"로 바꿈
    CONSTRAINT ck_messages_content CHECK (content IS NOT NULL AND char_length(content) BETWEEN 1 AND 2000)
);

-- 대화방 메시지 내역 · 마지막 메시지 · 안 읽은 수 조회용 (id 순서 = 메시지 순서)
CREATE INDEX ix_messages_conversation_id ON messages (conversation_id, id);

ALTER TABLE conversation_members
    ADD CONSTRAINT fk_conversation_members_last_read_message
        FOREIGN KEY (last_read_message_id) REFERENCES messages (id) ON DELETE SET NULL;
