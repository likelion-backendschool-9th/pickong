-- 저장 장소(찜). savedplace 모듈의 SavedPlaceJpaEntity와 같은 컬럼만 만듭니다.
-- 개인 사진 · 태그 · 컬렉션 연결 테이블은 조회에 필요하지 않아 만들지 않습니다.
-- V13(신고)은 #125에서 쓰고 있어 V14입니다. #125가 먼저 병합되어야 합니다.

CREATE TABLE saved_places (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id),
    place_id        BIGINT      NOT NULL REFERENCES places (id),
    memo            TEXT,
    visit_status    VARCHAR(20) NOT NULL DEFAULT 'WANT_TO_GO',
    visited_at      TIMESTAMPTZ,
    -- 저장 출처. 값 목록이 확정 전이라 CHECK를 두지 않습니다 (backend_blueprint.md 8.7 #2)
    source          VARCHAR(30),
    -- source가 FEED일 때만 있는 원본 게시물
    source_feed_id  BIGINT      REFERENCES feeds (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- 회원당 장소 1번. user_id로 시작해 내 목록 조회에도 쓰입니다.
    CONSTRAINT uk_saved_places_user_place UNIQUE (user_id, place_id),
    CONSTRAINT ck_saved_places_visit_status CHECK (visit_status IN ('WANT_TO_GO', 'VISITED', 'NOT_INTERESTED')),
    CONSTRAINT ck_saved_places_source_feed CHECK (source_feed_id IS NULL OR source = 'FEED')
);

CREATE INDEX ix_saved_places_place_id ON saved_places (place_id);
