-- 공개 장소 마스터. place 모듈의 PlaceJpaEntity와 같은 컬럼만 만듭니다.
-- 영업시간 · 외부 참조 테이블은 승인에 필요하지 않아 만들지 않습니다.
-- visibility, owner_id는 엔티티와 ERD에 아직 없어 추가하지 않습니다.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE places (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    UUID         NOT NULL DEFAULT gen_random_uuid(),
    name         TEXT         NOT NULL,
    address      TEXT,
    -- 경도, 위도. geography는 위도 -90~90, 경도 -180~180만 받습니다.
    location     GEOGRAPHY(POINT, 4326) NOT NULL,
    category     VARCHAR(30),
    source_type  VARCHAR(20)  NOT NULL,
    external_id  TEXT,
    phone        TEXT,
    website_url  TEXT,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_places_public_id UNIQUE (public_id),
    CONSTRAINT ck_places_name_not_blank CHECK (btrim(name) <> '')
);
