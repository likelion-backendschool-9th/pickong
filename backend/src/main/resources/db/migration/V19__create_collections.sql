-- 컬렉션 · 구성 장소. collection 모듈의 CollectionJpaEntity · CollectionPlaceJpaEntity와 같은 컬럼만 만듭니다.
-- 버전(collection_versions …) · 구매(collection_purchases) 테이블은 유료 컬렉션 작업에서 추가합니다.

CREATE TABLE collections (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id        UUID         NOT NULL DEFAULT gen_random_uuid(),
    user_id          BIGINT       NOT NULL REFERENCES users (id),
    -- 글자 수 규칙(화면은 30자)은 만들기 API와 함께 domain에 둡니다. 컬럼은 여유 있게 잡습니다.
    title            VARCHAR(100) NOT NULL,
    description      TEXT,
    visibility       VARCHAR(20)  NOT NULL DEFAULT 'PUBLIC',
    -- 탐색 화면 노출 여부
    is_listed        BOOLEAN      NOT NULL DEFAULT FALSE,
    is_pinned        BOOLEAN      NOT NULL DEFAULT FALSE,
    -- 지도 핀 색. 프론트 PinColor와 같은 값
    pin_style        VARCHAR(20)  NOT NULL DEFAULT 'LIME',
    -- 없으면 첫 장소의 사진을 표지로 보여 줍니다(조회에서 계산)
    cover_image_url  TEXT,
    -- NULL이면 무료
    price            INTEGER,
    place_count      INTEGER      NOT NULL DEFAULT 0,
    -- 관리자 숨김
    hidden_at        TIMESTAMPTZ,
    deleted_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_collections_public_id UNIQUE (public_id),
    CONSTRAINT ck_collections_visibility CHECK (visibility IN ('PUBLIC', 'FOLLOWERS', 'PRIVATE')),
    CONSTRAINT ck_collections_pin_style CHECK (pin_style IN ('LIME', 'GREEN', 'BROWN')),
    -- CollectionPrice와 같은 규칙: 500~50,000원, 100원 단위
    CONSTRAINT ck_collections_price CHECK (price IS NULL OR (price BETWEEN 500 AND 50000 AND price % 100 = 0)),
    CONSTRAINT ck_collections_place_count CHECK (place_count >= 0)
);

-- 프로필 · 내 컬렉션 목록 (회원별 최신순)
CREATE INDEX ix_collections_user_created ON collections (user_id, created_at DESC) WHERE deleted_at IS NULL;

CREATE TABLE collection_places (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id   BIGINT      NOT NULL REFERENCES collections (id) ON DELETE CASCADE,
    -- 저장 장소를 지울 때는 앱이 SavedPlaceDeletingEvent로 먼저 정리합니다. DB는 막아 둡니다 (blueprint 8.4 #8)
    saved_place_id  BIGINT      NOT NULL REFERENCES saved_places (id) ON DELETE RESTRICT,
    -- 저장 장소에서 복사한 값. 표지 · 장소 표시 조회에 씁니다
    place_id        BIGINT      NOT NULL REFERENCES places (id) ON DELETE RESTRICT,
    -- 앞 2곳이 미리보기. 순서 바꾸기 중간에 겹칠 수 있어 UNIQUE를 두지 않습니다 (blueprint 8.4 #4)
    sort_order      INTEGER     NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_collection_places_saved_place UNIQUE (collection_id, saved_place_id)
);

CREATE INDEX ix_collection_places_saved_place_id ON collection_places (saved_place_id);
