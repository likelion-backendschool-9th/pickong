-- 관리자 계정과 작업 기록. 운영용 계정/비밀번호는 마이그레이션에 넣지 않습니다.
-- 기존 reports.handled_by, place_submissions.reviewer_admin_id에는 과거 데이터 검증 없이 FK를 추가하지 않습니다.

CREATE TABLE admins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_admins_username UNIQUE (username),
    CONSTRAINT ck_admins_username_not_blank CHECK (btrim(username) <> ''),
    CONSTRAINT ck_admins_password_hash_not_blank CHECK (btrim(password_hash) <> ''),
    CONSTRAINT ck_admins_role CHECK (role IN ('SUPER_ADMIN', 'OPERATOR', 'CS')),
    CONSTRAINT ck_admins_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE admin_action_logs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id         BIGINT       NOT NULL,
    action_type      VARCHAR(255) NOT NULL,
    target_type      VARCHAR(255),
    -- 여러 모듈의 내부 BIGINT id. 공개 UUID를 넣지 않으며 다형 대상에는 FK를 걸지 않습니다.
    target_id        BIGINT,
    detail           TEXT,
    reason           TEXT,
    -- NULL이면 직접 처리, 값이 있으면 해당 신고에서 발생한 작업입니다.
    source_report_id BIGINT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_admin_action_logs_admin FOREIGN KEY (admin_id) REFERENCES admins (id) ON DELETE RESTRICT,
    CONSTRAINT fk_admin_action_logs_source_report FOREIGN KEY (source_report_id) REFERENCES reports (id) ON DELETE RESTRICT,
    CONSTRAINT ck_admin_action_logs_action_not_blank CHECK (btrim(action_type) <> ''),
    CONSTRAINT ck_admin_action_logs_target CHECK (
        (target_type IS NULL AND target_id IS NULL)
        OR (target_type IS NOT NULL AND btrim(target_type) <> '' AND target_id IS NOT NULL AND target_id > 0)
    ),
    -- UTF-8 char_length는 Unicode 코드 포인트 수입니다. Unicode 공백만인 사유도 거절합니다.
    CONSTRAINT ck_admin_action_logs_reason CHECK (
        reason IS NULL OR (
            char_length(reason) <= 200
            AND btrim(reason, U&'\0009\000A\000B\000C\000D\001C\001D\001E\001F\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000') <> ''
        )
    )
);

CREATE INDEX ix_admin_action_logs_admin_created_at ON admin_action_logs (admin_id, created_at DESC, id DESC);
CREATE INDEX ix_admin_action_logs_target_created_at ON admin_action_logs (target_type, target_id, created_at DESC, id DESC);
CREATE INDEX ix_admin_action_logs_source_report ON admin_action_logs (source_report_id) WHERE source_report_id IS NOT NULL;

-- 업무 변경과 같은 트랜잭션에서 호출자가 한 번만 기록합니다.
