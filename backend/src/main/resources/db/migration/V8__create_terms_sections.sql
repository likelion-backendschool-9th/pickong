-- 약관 본문(조항). 조항은 약관 버전 한 행(terms.id)에 묶이므로, 회원이 동의한 버전의 내용이 그대로 남습니다.
-- 문구를 바꿀 때는 이 파일을 고치지 않고, terms에 새 버전 행과 그 조항을 넣는 새 마이그레이션을 추가합니다.
CREATE TABLE terms_sections (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terms_id BIGINT       NOT NULL REFERENCES terms (id),
    position INT          NOT NULL,
    heading  VARCHAR(255) NOT NULL,
    body     TEXT         NOT NULL,

    CONSTRAINT uk_terms_sections_terms_id_position UNIQUE (terms_id, position)
);

