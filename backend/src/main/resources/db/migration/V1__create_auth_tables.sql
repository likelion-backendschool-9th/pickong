-- 인증에 필요한 테이블: 회원 · 소셜 로그인 수단 · 리프레시 토큰 · 약관 · 약관 동의
-- 나머지 테이블은 각 모듈 담당자가 V2부터 추가합니다.
-- 회원 행은 온보딩을 마친 시점에 만들어지므로 '온보딩 완료 여부' 컬럼은 두지 않습니다.

-- ── users (user 모듈) ─────────────────────────────────────
CREATE TABLE users (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id               UUID         NOT NULL DEFAULT gen_random_uuid(),
    -- 닉네임 = 사용자 ID. 영문 소문자로 저장하고, 대소문자 무시 UNIQUE는 아래 함수 인덱스로 보장합니다.
    username                VARCHAR(20)  NOT NULL,
    -- 가입한 소셜 계정의 인증된 이메일. 제공자가 주지 않으면 NULL
    email                   VARCHAR(255),
    -- 소셜 로그인 전용이라 지금은 쓰지 않습니다. (ERD 유지)
    password_hash           VARCHAR(255),
    -- 이름: 중복 가능, 정하지 않으면 NULL (화면에는 닉네임이 대신 보임)
    display_name            VARCHAR(30),
    bio                     TEXT,
    profile_image_url       TEXT,
    status                  VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    suspended_until         TIMESTAMPTZ,
    follower_count          BIGINT       NOT NULL DEFAULT 0,
    following_count         BIGINT       NOT NULL DEFAULT 0,
    feed_count              BIGINT       NOT NULL DEFAULT 0,
    withdrawal_requested_at TIMESTAMPTZ,
    deleted_at              TIMESTAMPTZ,
    last_login_at           TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_users_public_id UNIQUE (public_id),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN_PENDING', 'WITHDRAWN')),
    CONSTRAINT ck_users_counts CHECK (follower_count >= 0 AND following_count >= 0 AND feed_count >= 0)
);

CREATE UNIQUE INDEX uk_users_username_lower ON users (lower(username));
-- 1인 1계정: 같은 이메일로 다른 계정을 만들 수 없습니다.
CREATE UNIQUE INDEX uk_users_email_lower ON users (lower(email)) WHERE email IS NOT NULL;

-- ── user_social_accounts (auth 모듈) ──────────────────────
CREATE TABLE user_social_accounts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    provider    VARCHAR(20)  NOT NULL,
    -- 제공자의 고유 사용자 식별자 (카카오 회원번호, Google sub)
    provider_id VARCHAR(255) NOT NULL,
    -- 이 소셜 계정의 인증된 이메일. 로그인 수단 화면 표시와 이메일 중복 확인에 씁니다.
    email       VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_user_social_accounts_provider CHECK (provider IN ('KAKAO', 'GOOGLE')),
    -- 같은 소셜 계정은 하나의 찜콩 계정에만 연결됩니다.
    CONSTRAINT uk_user_social_accounts_provider_id UNIQUE (provider, provider_id),
    -- 한 찜콩 계정에는 제공자마다 하나만 연결합니다.
    CONSTRAINT uk_user_social_accounts_user_provider UNIQUE (user_id, provider)
);

-- 같은 회원의 카카오 · Google 이메일은 같을 수 있어서 UNIQUE가 아닌 조회용 인덱스입니다.
-- 다른 회원과 겹치는지는 가입 · 연결 시 서비스에서 확인합니다.
CREATE INDEX ix_user_social_accounts_email_lower ON user_social_accounts (lower(email)) WHERE email IS NOT NULL;

-- ── refresh_tokens (auth 모듈) ────────────────────────────
CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    -- 토큰 원문은 저장하지 않고 SHA-256 해시만 저장합니다.
    token_hash VARCHAR(255) NOT NULL,
    -- 한 번의 로그인에서 로테이션으로 이어진 토큰 묶음. 재사용이 감지되면 family 전체를 폐기합니다.
    family     VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_family ON refresh_tokens (family);

-- ── terms (terms 모듈) ────────────────────────────────────
CREATE TABLE terms (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(20)  NOT NULL,
    version      VARCHAR(255) NOT NULL,
    title        VARCHAR(255) NOT NULL,
    content_url  TEXT         NOT NULL,
    is_required  BOOLEAN      NOT NULL,
    effective_at TIMESTAMPTZ  NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_terms_type CHECK (type IN ('SERVICE', 'PRIVACY', 'MARKETING')),
    CONSTRAINT uk_terms_type_version UNIQUE (type, version)
);

-- ── user_terms_agreements (terms 모듈) ────────────────────
-- 동의 · 철회 이력을 남기므로 (user_id, terms_id)는 UNIQUE가 아닙니다.
CREATE TABLE user_terms_agreements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    terms_id   BIGINT      NOT NULL REFERENCES terms (id),
    agreed_at  TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);

CREATE INDEX ix_user_terms_agreements_user_id ON user_terms_agreements (user_id);
