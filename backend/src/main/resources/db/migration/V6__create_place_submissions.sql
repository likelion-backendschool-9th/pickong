-- 좌표 장소 제보. 대기 · 반려는 places에 넣지 않고, 승인할 때만 place_id를 연결합니다.
-- 관리자 목록은 1차에서 배열 전체로 조회합니다. 페이지 컬럼은 두지 않습니다.
-- reviewer_admin_id는 admins 테이블 마이그레이션이 아직 없어 FK를 걸지 않습니다.

CREATE TABLE place_submissions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitter_user_id  BIGINT       NOT NULL REFERENCES users (id),
    name               TEXT         NOT NULL,
    address            TEXT,
    category           VARCHAR(30)  NOT NULL,
    description        TEXT,
    image_url          TEXT,
    location           GEOGRAPHY(POINT, 4326) NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    submitted_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    reviewer_admin_id  BIGINT,
    reviewed_at        TIMESTAMPTZ,
    reject_reason      TEXT,
    place_id           BIGINT       REFERENCES places (id),

    CONSTRAINT ck_place_submissions_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_place_submissions_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_place_submissions_description_length CHECK (description IS NULL OR char_length(description) <= 200),
    CONSTRAINT ck_place_submissions_reject_reason_length CHECK (reject_reason IS NULL OR char_length(reject_reason) <= 200),
    CONSTRAINT ck_place_submissions_review_state CHECK (
        (
            status = 'PENDING'
            AND reviewed_at IS NULL
            AND reviewer_admin_id IS NULL
            AND reject_reason IS NULL
            AND place_id IS NULL
        )
        OR (
            status = 'APPROVED'
            AND reviewed_at IS NOT NULL
            AND reviewer_admin_id IS NOT NULL
            AND reject_reason IS NULL
            AND place_id IS NOT NULL
        )
        OR (
            status = 'REJECTED'
            AND reviewed_at IS NOT NULL
            AND reviewer_admin_id IS NOT NULL
            AND btrim(reject_reason) <> ''
            AND place_id IS NULL
        )
    )
);

CREATE INDEX ix_place_submissions_submitter_user_id ON place_submissions (submitter_user_id);
CREATE INDEX ix_place_submissions_place_id ON place_submissions (place_id);
CREATE INDEX ix_place_submissions_submitted_at ON place_submissions (submitted_at);
