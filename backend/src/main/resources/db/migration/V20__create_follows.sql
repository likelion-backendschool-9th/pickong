-- 팔로우 관계. social 모듈의 FollowJpaEntity와 같은 컬럼만 만듦
-- 이 테이블이 없어 팔로잉 피드(GET /feeds?tab=following)와 팔로우 API가 500이었음

CREATE TABLE follows (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 팔로우하는 사람
    follower_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- 팔로우받는 사람
    followee_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- 같은 사람을 두 번 팔로우할 수 없음. follower_id로 시작해 팔로잉 피드 조회에도 이 인덱스를 씀
    CONSTRAINT uk_follows_follower_followee UNIQUE (follower_id, followee_id),
    -- 자기 자신은 팔로우할 수 없음 (blueprint 8장 #10)
    CONSTRAINT ck_follows_not_self CHECK (follower_id <> followee_id)
);

-- 나를 팔로우하는 사람 목록 조회용
CREATE INDEX ix_follows_followee_id ON follows (followee_id);
