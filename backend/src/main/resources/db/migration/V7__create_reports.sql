-- 신고. 대상은 게시물 · 댓글 · 회원 · 컬렉션을 한 테이블이 가리키므로 target_id에는 FK를 걸지 않습니다.
-- 처리 액션과 상태는 따로 둡니다. 이번 앱은 기각(DISMISS)만 RESOLVED로 저장합니다.
-- handled_by는 admins 테이블이 아직 없어 제보의 reviewer_admin_id와 같이 FK를 걸지 않습니다.
-- reporter_id는 회원 행이 있어야 합니다. 회원은 소프트 삭제라 신고를 같이 지우는 CASCADE는 쓰지 않습니다.

CREATE TABLE reports (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id        BIGINT       NOT NULL REFERENCES users (id),
    target_type        VARCHAR(30)  NOT NULL,
    target_id          BIGINT       NOT NULL,
    reason             VARCHAR(50)  NOT NULL,
    detail             TEXT,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    resolution_action  VARCHAR(30),
    resolution_memo    TEXT,
    handled_by         BIGINT,
    handled_at         TIMESTAMPTZ,
    snapshot           TEXT,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_reports_target_type CHECK (target_type IN ('FEED', 'COMMENT', 'USER', 'COLLECTION')),
    CONSTRAINT ck_reports_status CHECK (status IN ('PENDING', 'RESOLVED')),
    CONSTRAINT ck_reports_resolution_action CHECK (
        resolution_action IS NULL
        OR resolution_action IN ('DISMISS', 'HIDE_CONTENT', 'SANCTION_USER')
    ),
    CONSTRAINT ck_reports_reason_not_blank CHECK (btrim(reason) <> ''),
    CONSTRAINT ck_reports_resolution_memo_length CHECK (
        resolution_memo IS NULL OR char_length(resolution_memo) <= 200
    ),
    CONSTRAINT ck_reports_resolution_state CHECK (
        (
            status = 'PENDING'
            AND resolution_action IS NULL
            AND resolution_memo IS NULL
            AND handled_by IS NULL
            AND handled_at IS NULL
        )
        OR (
            status = 'RESOLVED'
            AND resolution_action IS NOT NULL
            AND handled_by IS NOT NULL
            AND handled_at IS NOT NULL
            AND (
                resolution_action = 'DISMISS'
                OR (resolution_memo IS NOT NULL AND btrim(resolution_memo) <> '')
            )
        )
    )
);

CREATE INDEX ix_reports_status_created_at ON reports (status, created_at DESC, id DESC);
CREATE INDEX ix_reports_target_status ON reports (target_type, target_id, status);
