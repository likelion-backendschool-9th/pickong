/** 라우트 경로 상수. 링크 문자열을 직접 쓰지 않고 이 함수를 사용합니다. */
export const routes = {
  start: () => "/",
  login: () => "/login",
  /** 전화번호로 회원가입(기본) */
  signup: () => "/signup",
  signupEmail: () => "/signup/email",
  passwordReset: () => "/password/reset",
  terms: (type: "service" | "privacy" | "marketing") => `/terms/${type}`,
  feed: () => "/feed",
  search: () => "/search",
  notifications: () => "/notifications",
  post: (id: string) => `/posts/${id}`,
  newPost: () => "/posts/new",
  map: (view?: "list") => (view ? `/map?view=${view}` : "/map"),
  place: (id: string) => `/places/${id}`,
  newPlace: () => "/places/new",
  myPlaces: () => "/places/mine",
  editPlace: (id: string) => `/places/${id}/edit`,
  placePhotos: (id: string) => `/places/${id}/photos`,
  placeTags: (id: string) => `/places/${id}/tags`,
  tags: () => "/tags",
  tag: (name: string) => `/tags/${encodeURIComponent(name)}`,
  collections: () => "/collections",
  newCollection: () => "/collections/new",
  collection: (id: string) => `/collections/${id}`,
  editCollection: (id: string) => `/collections/${id}/edit`,
  importLink: () => "/import",
  /** 일정 목록은 내 프로필의 일정 탭에 있습니다. username을 모르면 /plans가 내 프로필로 보냅니다. */
  plans: () => "/plans",
  myPlans: (username: string) => `/users/${username}?tab=plans`,
  newPlan: (placeIds?: string[]) =>
    placeIds?.length ? `/plans/new?places=${placeIds.join(",")}` : "/plans/new",
  plan: (id: string) => `/plans/${id}`,
  planVisits: (id: string) => `/plans/${id}/visits`,
  messages: () => "/messages",
  conversation: (id: string) => `/messages/${id}`,
  groupChats: () => "/messages/groups",
  newGroupChat: () => "/messages/groups/new",
  groupChat: (id: string) => `/messages/groups/${id}`,
  user: (username: string) => `/users/${username}`,
  follows: (username: string, tab: "followers" | "following") => `/users/${username}/follows?tab=${tab}`,
  settings: () => "/settings",
  editProfile: () => "/settings/profile",
  agreements: () => "/settings/agreements",
  notificationSettings: () => "/settings/notifications",
  devices: () => "/settings/devices",
  withdraw: () => "/settings/withdraw",
  checkout: (collectionId: string) => `/checkout/${collectionId}`,
  purchases: () => "/purchases",
  refund: (purchaseId: string) => `/purchases/${purchaseId}/refund`,
  creator: () => "/creator",
  creatorApply: () => "/creator/apply",
  creatorAccount: () => "/creator/account",
  creatorEarnings: () => "/creator/earnings",
  admin: () => "/admin",
  adminReports: () => "/admin/reports",
  adminUsers: () => "/admin/users",
  adminContents: () => "/admin/contents",
  adminCreators: () => "/admin/creators",
  adminRefunds: () => "/admin/refunds",
  adminSettlements: () => "/admin/settlements",
} as const;
